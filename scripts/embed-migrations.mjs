// Bundles drizzle/*.sql into a TypeScript module so the app can apply
// migrations at runtime on serverless hosts (no filesystem reads needed).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const files = readdirSync("drizzle").filter((f) => f.endsWith(".sql")).sort();
const migrations = files.map((name) => ({
  name,
  statements: readFileSync(`drizzle/${name}`, "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
}));

writeFileSync(
  "src/lib/db/migrations.generated.ts",
  `// Generated by scripts/embed-migrations.mjs. Do not edit by hand.\n` +
    `export const migrations: { name: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Embedded ${migrations.length} migration(s).`);
